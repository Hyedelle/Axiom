# Axiom Autonomous Monitor & Health Reporter
# Usage: powershell -ExecutionPolicy Bypass -File tools/monitor.ps1

$ErrorActionPreference = "Continue"

$ProjectRoot = Resolve-Path (Join-Path $PSScriptRoot "..")
Set-Location $ProjectRoot

$TmpDir = Join-Path $ProjectRoot "tmp"
if (-not (Test-Path $TmpDir)) {
    New-Item -ItemType Directory -Path $TmpDir -Force | Out-Null
}

$DashboardFile = Join-Path $ProjectRoot "docs\dashboard.md"
$StatusFile = Join-Path $TmpDir "monitor_status.txt"

Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host "Axiom Engine Autonomous Health Monitor Daemon" -ForegroundColor Cyan
Write-Host "==========================================================" -ForegroundColor Cyan

# 1. Run Mechanical Constitutional Guard
Write-Host "==> [Phase 1/3] Running Constitutional Guard..." -ForegroundColor Yellow
& powershell -ExecutionPolicy Bypass -File tools/guard.ps1
$GuardCode = $LASTEXITCODE

if ($GuardCode -ne 0) {
    Write-Host "[FAIL] Guard check failed with exit code $GuardCode" -ForegroundColor Red
    Set-Content -Path $StatusFile -Value "MONITOR_FAIL: Guard violation" -Encoding UTF8
    exit $GuardCode
}

# 2. Gather Git Telemetry
Write-Host "==> [Phase 2/3] Gathering Git Repository Telemetry..." -ForegroundColor Yellow
$CommitCount = (git rev-list --count HEAD).Trim()
$LatestHash = (git rev-parse --short HEAD).Trim()
$LatestSubject = (git log -1 --pretty=format:"%s").Trim()
$DateStr = Get-Date -Format "yyyy-MM-dd HH:mm:ss"

# Dynamically parse workspace version from Cargo.toml
$CargoContent = Get-Content -Path "$ProjectRoot/Cargo.toml" -Raw
$WorkspaceVersion = "1.0.0"
if ($CargoContent -match '\[workspace\.package\][\s\S]*?version\s*=\s*"([^"]+)"') {
    $WorkspaceVersion = $matches[1]
}

# 3. Generate Dashboard Markdown
Write-Host "==> [Phase 3/3] Generating Dashboard ($DashboardFile)..." -ForegroundColor Yellow

$RecentCommits = (git log --oneline -n 5) -join "`n"

$DashboardContent = @"
